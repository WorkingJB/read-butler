-- Read Butler: initial schema.
-- Every table is owned per user and protected by row level security, so both
-- the web app and the Chrome extension talk to Supabase directly with the
-- user's JWT. No service-role key is used anywhere in the clients.

-- ---------------------------------------------------------------------------
-- Profiles: one row per auth user, holding reader preferences.
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text check (char_length(display_name) <= 100),
  target_wpm integer not null default 300 check (target_wpm between 50 and 1500),
  ramp_enabled boolean not null default true,
  ramp_start_wpm integer not null default 250 check (ramp_start_wpm between 50 and 1500),
  ramp_step_wpm integer not null default 25 check (ramp_step_wpm between 5 and 200),
  ramp_step_words integer not null default 150 check (ramp_step_words between 25 and 5000),
  font_scale real not null default 1 check (font_scale between 0.5 and 3),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Create a profile whenever someone signs up.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id) values (new.id);
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- Documents: library metadata. The body lives in document_contents so that
-- listing the library never pulls megabytes of text.
-- ---------------------------------------------------------------------------
create type public.document_source as enum ('paste', 'file', 'url', 'selection');

create table public.documents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title text not null check (char_length(title) between 1 and 300),
  source_type public.document_source not null,
  source_name text check (char_length(source_name) <= 2000),
  word_count integer not null check (word_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index documents_user_created_idx on public.documents (user_id, created_at desc);

create table public.document_contents (
  document_id uuid primary key references public.documents (id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  body text not null check (char_length(body) between 1 and 3000000),
  -- [{ "title": "Chapter 1", "wordIndex": 0 }, ...]
  sections jsonb not null default '[]'::jsonb check (jsonb_typeof(sections) = 'array')
);

create index document_contents_user_idx on public.document_contents (user_id);

-- ---------------------------------------------------------------------------
-- Reading progress: where the user left off in each document.
-- ---------------------------------------------------------------------------
create table public.reading_progress (
  document_id uuid primary key references public.documents (id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  word_index integer not null default 0 check (word_index >= 0),
  wpm integer check (wpm between 50 and 1500),
  completed_at timestamptz,
  updated_at timestamptz not null default now()
);

create index reading_progress_user_idx on public.reading_progress (user_id, updated_at desc);

-- ---------------------------------------------------------------------------
-- Reading sessions: one row per sitting, used for stats and speed training.
-- The id is generated by the client so checkpoints can upsert the same row.
-- ---------------------------------------------------------------------------
create table public.reading_sessions (
  id uuid primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  document_id uuid references public.documents (id) on delete set null,
  client text not null default 'web' check (client in ('web', 'extension')),
  started_at timestamptz not null,
  ended_at timestamptz not null,
  start_word_index integer not null check (start_word_index >= 0),
  end_word_index integer not null check (end_word_index >= 0),
  words_read integer not null check (words_read >= 0),
  active_ms integer not null check (active_ms >= 0),
  start_wpm integer not null check (start_wpm between 50 and 1500),
  end_wpm integer not null check (end_wpm between 50 and 1500),
  -- Optional 1-5 self rating, which drives the next session's target speed.
  comprehension smallint check (comprehension between 1 and 5),
  check (ended_at >= started_at)
);

create index reading_sessions_user_started_idx on public.reading_sessions (user_id, started_at desc);
create index reading_sessions_document_idx on public.reading_sessions (document_id);

-- Words per day and effective speed, for the stats page.
create view public.daily_reading_stats
with (security_invoker = true)
as
select
  user_id,
  (started_at at time zone 'utc')::date as day,
  sum(words_read)::integer as words_read,
  sum(active_ms)::bigint as active_ms,
  case when sum(active_ms) > 0
    then round(sum(words_read) * 60000.0 / sum(active_ms))::integer
  end as effective_wpm
from public.reading_sessions
group by user_id, (started_at at time zone 'utc')::date;

-- ---------------------------------------------------------------------------
-- updated_at maintenance
-- ---------------------------------------------------------------------------
create function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_touch before update on public.profiles
  for each row execute function public.touch_updated_at();
create trigger documents_touch before update on public.documents
  for each row execute function public.touch_updated_at();
create trigger reading_progress_touch before update on public.reading_progress
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- create_document: inserts metadata and body in one transaction. Runs as the
-- caller, so RLS still applies. The word count is computed here with the same
-- whitespace rule as the client tokenizer, so stored indexes stay consistent.
-- ---------------------------------------------------------------------------
create function public.create_document(
  p_title text,
  p_source_type public.document_source,
  p_body text,
  p_source_name text default null,
  p_sections jsonb default '[]'::jsonb
)
returns public.documents
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_doc public.documents;
  v_body text := btrim(p_body);
begin
  if v_body = '' then
    raise exception 'Document body is empty';
  end if;

  insert into public.documents (title, source_type, source_name, word_count)
  values (
    left(btrim(p_title), 300),
    p_source_type,
    p_source_name,
    coalesce(array_length(regexp_split_to_array(v_body, '\s+'), 1), 0)
  )
  returning * into v_doc;

  insert into public.document_contents (document_id, body, sections)
  values (v_doc.id, v_body, coalesce(p_sections, '[]'::jsonb));

  return v_doc;
end;
$$;

-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.documents enable row level security;
alter table public.document_contents enable row level security;
alter table public.reading_progress enable row level security;
alter table public.reading_sessions enable row level security;

create policy "Users read own profile" on public.profiles
  for select to authenticated using ((select auth.uid()) = id);
create policy "Users update own profile" on public.profiles
  for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create policy "Users read own documents" on public.documents
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users create own documents" on public.documents
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Users update own documents" on public.documents
  for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Users delete own documents" on public.documents
  for delete to authenticated using ((select auth.uid()) = user_id);

-- Child rows must point at a document the user owns, so nobody can claim
-- another user's document id.
create policy "Users read own contents" on public.document_contents
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users create contents for own documents" on public.document_contents
  for insert to authenticated with check (
    (select auth.uid()) = user_id
    and exists (select 1 from public.documents d where d.id = document_id and d.user_id = (select auth.uid()))
  );

create policy "Users read own progress" on public.reading_progress
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users create own progress" on public.reading_progress
  for insert to authenticated with check (
    (select auth.uid()) = user_id
    and exists (select 1 from public.documents d where d.id = document_id and d.user_id = (select auth.uid()))
  );
create policy "Users update own progress" on public.reading_progress
  for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create policy "Users read own sessions" on public.reading_sessions
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users create own sessions" on public.reading_sessions
  for insert to authenticated with check (
    (select auth.uid()) = user_id
    and (
      document_id is null
      or exists (select 1 from public.documents d where d.id = document_id and d.user_id = (select auth.uid()))
    )
  );
-- Clients generate the session id and upsert the same row at each checkpoint.
create policy "Users update own sessions" on public.reading_sessions
  for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Users delete own sessions" on public.reading_sessions
  for delete to authenticated using ((select auth.uid()) = user_id);

-- ---------------------------------------------------------------------------
-- Grants: signed-in users only. Anonymous visitors use the local-only reader.
-- ---------------------------------------------------------------------------
revoke all on public.profiles, public.documents, public.document_contents,
  public.reading_progress, public.reading_sessions, public.daily_reading_stats from anon;

grant select on public.profiles to authenticated;
grant update (display_name, target_wpm, ramp_enabled, ramp_start_wpm, ramp_step_wpm, ramp_step_words, font_scale)
  on public.profiles to authenticated;
grant select, insert, delete on public.documents to authenticated;
grant update (title) on public.documents to authenticated;
grant select, insert on public.document_contents to authenticated;
grant select, insert, update on public.reading_progress to authenticated;
grant select, insert, update, delete on public.reading_sessions to authenticated;
grant select on public.daily_reading_stats to authenticated;

revoke execute on function public.create_document(text, public.document_source, text, text, jsonb) from public, anon;
grant execute on function public.create_document(text, public.document_source, text, text, jsonb) to authenticated;
revoke execute on function public.handle_new_user() from public, anon, authenticated;
